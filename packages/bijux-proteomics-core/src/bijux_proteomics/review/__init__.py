_REVIEW_EXPORTS_BY_NAME = {
    name: module_path
    for module_path, names in _REVIEW_EXPORTS_BY_MODULE.items()
    for name in names
}


def __getattr__(name: str) -> Any:
    module_path = _REVIEW_EXPORTS_BY_NAME.get(name)
    if module_path is None:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    module = import_module(module_path)
    value = getattr(module, name)
    globals()[name] = value
    return value


__all__ = list(_REVIEW_EXPORTS_BY_NAME)
